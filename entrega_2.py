"""#Limpieza de datos"""

#1 Valores faltantes o eliminacion de datos o columnas

#Eliminar campo que no necesito,porque no existe data para intervenir ni llenar con info que no es
df = df.drop(columns=["Animal code"])

#Elimino registros incompletos en su mayoria, aquellos que tienen 9 mas columnas vacias
df = df.dropna(thresh=9)

#Elimina duplicados

df = df.drop_duplicates()


#Variables categoricas - Se hara un refill como desconocidos para los campos nulos
categoricas = ["Animal type","Country","Gender","Animal name"]

for col in categoricas:
  df[col] = df[col].fillna("Unknown")


#Variables numericas

numericos = ["Weight kg","Body Length cm","Latitude","Longitude"]

for col in numericos:
  df[col] = df[col].fillna(df[col].median())


#Convierte tipo de datos
df['Observation date'] = pd.to_datetime(df['Observation date'],errors='coerce')

df.head()

df.isnull().sum()

#Se puede evidencia los campos que fueron tratados.
#Para el caso de Obseration Date, habian datos inconsistentes 385 lo que no dejaba hacer la transformacion a fecha

"""#Transformacion de datos"""

#Homologacion de nombres de tipo animal
animal_type_replacements = {
    'ledgehod': 'hedgehog',
    'lynx?': 'lynx',
    'red squirel': 'red squirrel',
    'red squirrell': 'red squirrel',
    'European bison™':'European bisson',
    'European bison ': 'European bisson'
}

df['Animal type'] = df['Animal type'].replace(animal_type_replacements)

#Media estadistica en el peso para categorizarlo

peso_promedio = np.mean(df['Weight kg'])

#Nueva variable usando np.where
df["Weight Category"] = np.where(
    df["Weight kg"] > peso_promedio,
    "Peso por encima del promedio",
    "Peso por debajo del promedio"
)

# Otra medida estadística
peso_mediano = np.nanmedian(df["Weight kg"])

print("Peso promedio:", peso_promedio)
print("Peso mediano:", peso_mediano)

"""#Analisis group by"""

#Quienes y cuantos animales han registrado cada uno?

display(df["Animal type"].groupby(df["Data compiled by"]).count())

#Promedio de Body Length cm por tipo animal

display(df.groupby('Animal type')['Body Length cm'].mean())

#Promedio Weight kg por pais

display(df.groupby('Country')['Weight kg'].mean())

