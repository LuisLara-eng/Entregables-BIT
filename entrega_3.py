plt.title('Distribución de Saldos según Estado Civil', fontsize=14, fontweight='bold')
plt.xlabel('Estado Civil', fontsize=12)
plt.ylabel('Saldo Medio Anual (Escala Logarítmica)', fontsize=12)
plt.show()
print("Interpretación P5: La distribución del balance según estado civil se mantiene con rangos similares, aunque el grupo de divorciados presenta valores atípicos negativos menores en comparación con solteros y casados.\n\n" + "="*80 + "\n")

