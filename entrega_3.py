# Configurar el estilo visual de los gráficos
sns.set_theme(style="whitegrid")
plt.rcParams['figure.figsize'] = (10, 6)

print("=== RESOLVIENDO PREGUNTAS DE ANÁLISIS ===\n")

# PREGUNTA 1: ¿Existe relación entre el nivel educativo y el saldo medio anual (balance) de los clientes?
plt.figure(figsize=(10, 5))
sns.barplot(data=df_data, x='education', y='balance', estimator=np.mean, errorbar=None, palette='viridis')
plt.title('Saldo Medio Anual según el Nivel Educativo', fontsize=14, fontweight='bold')
plt.xlabel('Nivel Educativo', fontsize=12)
plt.ylabel('Saldo Medio Anual (Euros)', fontsize=12)
plt.show()
print("Interpretación P1: Los clientes con educación terciaria mantienen, en promedio, un saldo medio anual significativamente superior (superando los 1600 euros) en comparación con aquellos con nivel educativo primaria o secundaria, demostrando una correlación positiva directa entre nivel académico y solvencia.\n\n" + "-"*80 + "\n")

# PREGUNTA 2: ¿Cómo influye el tener un préstamo hipotecario (housing) en el éxito de la campaña actual (y)?
plt.figure(figsize=(10, 5))
sns.countplot(data=df_data, x='housing', hue='y', palette='Set2')
plt.title('Suscripción al Depósito según Préstamo Hipotecario', fontsize=14, fontweight='bold')
plt.xlabel('¿Tiene Préstamo Hipotecario?', fontsize=12)
plt.ylabel('Cantidad de Clientes', fontsize=12)
plt.legend(title='¿Se suscribió?')
plt.show()
print("Interpretación P2: Los clientes que no poseen una hipoteca activa muestran una tasa de conversión superior. La presión de deuda hipotecaria restringe la liquidez de los clientes para comprometerse con nuevos depósitos bancarios.\n\n" + "-"*80 + "\n")

# PREGUNTA 3: ¿Cuáles son las categorías laborales (job) con mejores saldos promedio y cómo se relacionan con la suscripción (y)?
plt.figure(figsize=(12, 6))
sns.barplot(data=df_data, x='balance', y='job', hue='y', estimator=np.mean, errorbar=None, palette='coolwarm')
plt.title('Saldo Promedio por Trabajo y Estado de Suscripción', fontsize=14, fontweight='bold')
plt.xlabel('Saldo Medio Anual (Euros)', fontsize=12)
plt.ylabel('Tipo de Trabajo', fontsize=12)
plt.legend(title='¿Suscrito?')
plt.tight_layout()
plt.show()
print("Interpretación P3: Quienes aceptan el producto (y='yes') registran típicamente saldos promedio más elevados dentro de sus mismos grupos ocupacionales, especialmente entre empresarios ('entrepreneur') y jubilados ('retired').\n\n" + "-"*80 + "\n")

# PREGUNTA 4: ¿Cómo afecta el canal de contacto utilizado (contact) en la duración promedio de las llamadas?
plt.figure(figsize=(10, 5))
sns.barplot(data=df_data, x='contact', y='duration', estimator=np.mean, errorbar=None, palette='pastel')
plt.title('Duración Promedio del Último Contacto según Canal', fontsize=14, fontweight='bold')
plt.xlabel('Canal de Comunicación', fontsize=12)
plt.ylabel('Duración promedio (segundos)', fontsize=12)
plt.show()
print("Interpretación P4: Las comunicaciones telefónicas directas (celular y teléfono tradicional) registran conversaciones considerablemente más largas en comparación con los contactos cuyo medio es 'desconocido' o comunicacion presencial.\n\n" + "-"*80 + "\n")

# PREGUNTA 5: ¿Existe alguna diferencia notable en la distribución del saldo según el estado civil?
plt.figure(figsize=(10, 5))
sns.boxplot(data=df_data, x='marital', y='balance', palette='Set3')
