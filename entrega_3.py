"""### Paso 2: Limpieza y Transformación de Datos

En este paso:
- No existen valores duplicados.
- Crearemos una nueva variable útil para el análisis, categorizar el saldo (`balance`) en rangos de balance (Bajo, Medio, Alto).
- Mostraremos un resumen del DataFrame resultante.
"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

print(f"Dimensiones del dataset: {df_data.shape[0]} filas y {df_data.shape[1]} columnas.\n")

print("--- Cantidad de valores nulos por columna ---")
print(df_data.isnull().sum())

duplicados = df_data.duplicated().sum()
print(f"\nCantidad de filas completamente duplicadas: {duplicados}")

if duplicados > 0:
    df_data = df_data.drop_duplicates()
    print("Duplicados eliminados con éxito.")
else:
    print("No se encontraron duplicados para eliminar.")

# 3. Transformación de columnas: Crear rango de edad
def clasificar_edad(edad):
    if edad < 30:
        return 'Jóvenes (<30)'
    elif edad <= 50:
        return 'Adultos (30-50)'
    else:
        return 'Mayores (>50)'

df_data['rango_edad'] = df_data['age'].apply(clasificar_edad)

# Crear rango de saldo (balance)
def clasificar_saldo(saldo):
    if saldo < 0:
        return 'Negativo'
    elif saldo <= 500:
        return 'Bajo (0-500)'
    elif saldo <= 2000:
        return 'Medio (501-2000)'
    else:
        return 'Alto (>2000)'

df_data['rango_saldo'] = df_data['balance'].apply(clasificar_saldo)

print("\nColumnas creadas: 'rango_edad' y 'rango_saldo'. Resumen de datos:")
display(df_data[['age', 'rango_edad', 'balance', 'rango_saldo']].head())

