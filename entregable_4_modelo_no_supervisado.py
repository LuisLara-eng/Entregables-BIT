"""### 3. Distribución de Horas por Usuario
Dado que los datos de horas de juego suelen estar muy sesgados por "hardcore gamers" que juegan miles de horas, se hara distribución de horas mediante un gráfico de caja (boxplot) y determinar el promedio de hora de juego por usuario
"""

# Calcular las horas promedio jugadas por cada usuario activo
hours_per_user = df_play.groupby('user_id')['hours'].sum()

plt.figure(figsize=(12, 5))
sns.boxplot(x=hours_per_user, color='skyblue')
plt.title('Distribución de Horas de Juego Totales por Usuario (Con Sesgo/Outliers)', fontsize=14)
plt.xlabel('Horas Totales Jugadas', fontsize=12)
plt.xscale('log') # Escala logarítmica para ver mejor la distribucion con usuarios que tienen muchas horas en juego mas que la media
plt.show()

print(f"El promedio de horas jugadas por usuario activo es: {hours_per_user.mean():.2f} horas.")
print(f"La mediana de horas jugadas por usuario activo es: {hours_per_user.median():.2f} horas.")

#Separar las compras y las horas de juego
compras = df[df["behavior"] == "purchase"].groupby("user_id")["game_name"].count().reset_index(name="total_compras")
horas = df[df["behavior"] == "play"].groupby("user_id")["hours"].sum().reset_index(name="total_horas")


df_usuarios = pd.merge(compras, horas, on="user_id", how="outer").fillna(0)

print(df_usuarios.describe())

#Debido que existen outliers por jugadores que tienen muchas horas en juego y auqellos que no hacen compras de juegos,
#puede sesgar el calculo y afectar la clasificación, por ende se aplica logaritmo para estabilizar el sesgo extremo

df_usuarios["total_compras"] = np.log1p(df_usuarios["total_compras"])
df_usuarios["total_horas"] = np.log1p(df_usuarios["total_horas"])

print(df_usuarios.describe())

# Escalar las columnas con StandardScaler
scaler = StandardScaler()
X_scaled = scaler.fit_transform(df_usuarios[['total_horas', 'total_compras']])

X_scaled

#Se entrenara los dos modelos buscando 4 grupos---
n_groups = 4

#Modelo 1 k-means
kmeans = KMeans(n_clusters = n_groups,random_state = 42)
df_usuarios['cluster_kmeans'] = kmeans.fit_predict(X_scaled)

#(Silhouette Score) Para poder comparar metricas, valores mas cercanos
#a 1 indican que estan mejor separados
sil_kmeans = silhouette_score(X_scaled, df_usuarios['cluster_kmeans'])

print(f"Silhouette Score K-Means: {sil_kmeans:.4f}")



#Modelo 2 jerarquia
hierarchical = AgglomerativeClustering(n_clusters = n_groups)
df_usuarios['cluster_hierarchical'] = hierarchical.fit_predict(X_scaled)

sil_hierarchical = silhouette_score(X_scaled, df_usuarios['cluster_hierarchical'])

print(f"Silhouette Score Jerarquico: {sil_hierarchical:.4f}")

if sil_kmeans > sil_hierarchical:
    print("El modelo K-Means es mejor.")
else:
    print("El modelo Jerárquico es mejor.")
