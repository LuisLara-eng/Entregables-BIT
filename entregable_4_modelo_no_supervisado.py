#Se realiza la segmentacion y se asigna nombre a cada grupo
#diccionario
mapeo_clusters = {
    1: 'Usuario Casual',
    0: 'Juega Activo sin compra recurrente',
    3: 'Comprador Regular',
    2: 'Usuario (VIP)'
}

#mapea renombrado en una nueva columna
df_usuarios['segmento_comercial'] = df_usuarios['cluster_kmeans'].map(mapeo_clusters)


df_usuarios.head()

# 3. Calcular cantidad de usuarios y porcentaje por grupo
tabla_porcentajes = df_usuarios['segmento_comercial'].value_counts().reset_index()
tabla_porcentajes.columns = ['Segmento', 'Cantidad de Usuarios']

total_usuarios = len(df)
tabla_porcentajes['Porcentaje (%)'] = (tabla_porcentajes['Cantidad de Usuarios'] / total_usuarios) * 100
tabla_porcentajes['Porcentaje (%)'] = tabla_porcentajes['Porcentaje (%)'].round(2)

metricas_perfil = df_usuarios.groupby('segmento_comercial')[['total_horas', 'total_compras']].median().reset_index()

metricas_perfil.columns = ['Segmento', 'Mediana Horas', 'Mediana Compras']

reporte_final = pd.merge(tabla_porcentajes, metricas_perfil, on='Segmento')

print(reporte_final.to_string(index=False))

